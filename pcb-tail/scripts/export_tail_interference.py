#!/usr/bin/env python3
"""Export M5 handle interference facts from pcb-tail KiCad board.

Writes enclosure/m5/build/tail_interference.json:
  - Edge.Cuts polygon (KiCad XY = handle XZ)
  - J1 / SW1 / D1 / LED1 poses + cut envelopes for shell boolean

  python3 pcb-tail/scripts/export_tail_interference.py
"""

# ===== 分区：导入/依赖 =====
from __future__ import annotations

import json
import sys
from pathlib import Path


# ===== 分区：常量/配置 =====
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
PCB = ROOT / "pcb-tail" / "layouts" / "default" / "default.kicad_pcb"
FACTS = ROOT / "pcb-tail" / "outline-facts.json"
OUT = ROOT / "enclosure" / "m5" / "build" / "tail_interference.json"
OUT_SCAD = ROOT / "enclosure" / "m5" / "tail_board_cuts_m5.scad"

# 开孔相对器件的间隙（mm）
USB_CLEAR = 0.35
BTN_HOLE_OVER = 0.50          # 按钮孔比按柱粗
LED_HOLE_OVER = 0.40
BOARD_AXIAL_CLEAR = 0.15      # 板厚向每侧


# ===== 分区：私有成员 =====
def _kicad_python() -> str:
    mac = Path(
        "/Applications/KiCad/KiCad.app/Contents/Frameworks/"
        "Python.framework/Versions/Current/bin/python3"
    )
    if mac.is_file():
        return str(mac)
    return sys.executable


def _extract() -> dict:
    import wx

    _app = wx.App(False)
    import pcbnew

    board = pcbnew.LoadBoard(str(PCB))
    facts = json.loads(FACTS.read_text(encoding="utf-8"))
    butt_y = float(facts["butt_y"])
    pcb_y = float(facts["pcb_y"])
    board_t = float(facts["board_thickness"])

    edge: list[list[float]] = []
    for dr in board.GetDrawings():
        if board.GetLayerName(dr.GetLayer()) != "Edge.Cuts":
            continue
        outline = dr.GetPolyShape().Outline(0)
        for i in range(outline.PointCount()):
            p = outline.CPoint(i)
            edge.append([p.x / 1e6, p.y / 1e6])
        break
    if len(edge) < 8:
        raise RuntimeError("Edge.Cuts polygon missing")

    def fp_pose(ref: str) -> dict:
        fp = board.FindFootprintByReference(ref)
        if fp is None:
            raise RuntimeError(f"missing footprint {ref}")
        p = fp.GetPosition()
        return {
            "ref": ref,
            "x": p.x / 1e6,
            "y": p.y / 1e6,
            "rot_deg": fp.GetOrientationDegrees(),
            "layer": board.GetLayerName(fp.GetLayer()),
        }

    j1 = fp_pose("J1")
    sw1 = fp_pose("SW1")
    d1 = fp_pose("D1")
    led1 = fp_pose("LED1")

    # 器件包络（与 lib/3dmodels/*.scad 对齐）
    usb = {
        **j1,
        "shell_w": 8.94,
        "shell_d": 3.26,
        "height": 5.80,
        "clear": USB_CLEAR,
    }
    button = {
        **sw1,
        "body": 4.5,
        "body_h": 3.20,
        "stem_d": 1.70,
        "act_d": 2.40,
        "act_h": 1.10,
        "hole_d": 2.40 + BTN_HOLE_OVER,
        "pocket": 4.5 + 0.6,
    }
    led_rgb = {
        **d1,
        "body": 2.0,
        "height": 1.08,
        "hole_d": 2.0 + LED_HOLE_OVER,
    }
    led_status = {
        **led1,
        "body_w": 1.6,
        "body_d": 0.8,
        "height": 0.8,
        "hole_d": 1.6 + LED_HOLE_OVER,
    }

    return {
        "source_pcb": str(PCB.relative_to(ROOT)),
        "butt_y": butt_y,
        "pcb_y": pcb_y,
        "board_thickness": board_t,
        "board_axial_clear": BOARD_AXIAL_CLEAR,
        "ring_groove_radial": float(facts["ring_groove_radial"]),
        "orientation": facts["orientation"],
        "edge_cuts_xy": edge,
        "usb": usb,
        "button": button,
        "led_rgb": led_rgb,
        "led_status": led_status,
        "transform": {
            "comment": "handle(x,y,z) = (kicad_x, pcb_y - kicad_z, kicad_y)",
            "kicad_z_toward_butt": True,
        },
    }


def _write_scad(data: dict) -> None:
    """OpenSCAD 可 include 的开孔参数（由 KiCad 位姿生成）。"""
    usb, btn = data["usb"], data["button"]
    d1, led1 = data["led_rgb"], data["led_status"]
    edge = data["edge_cuts_xy"]
    pts = ",\n".join(f"    [{x:.5f}, {y:.5f}]" for x, y in edge)
    text = f"""// AUTO-GENERATED by pcb-tail/scripts/export_tail_interference.py — do not edit
// KiCad XY → handle XZ；F.Cu @ pcb_y；+Z_kicad 朝拍尾 (−Y)

m5_if_pcb_y = {data['pcb_y']:.6f};
m5_if_butt_y = {data['butt_y']:.6f};
m5_if_board_t = {data['board_thickness']:.3f};
m5_if_axial = {data['board_axial_clear']:.3f};

m5_if_usb_x = {usb['x']:.5f};
m5_if_usb_z = {usb['y']:.5f};
m5_if_usb_w = {usb['shell_w'] + 2 * usb['clear']:.3f};
m5_if_usb_d = {usb['shell_d'] + 2 * usb['clear']:.3f};

m5_if_btn_x = {btn['x']:.5f};
m5_if_btn_z = {btn['y']:.5f};
m5_if_btn_hole_d = {btn['hole_d']:.3f};
m5_if_btn_pocket = {btn['pocket']:.3f};
m5_if_btn_body_h = {btn['body_h']:.3f};

m5_if_d1_x = {d1['x']:.5f};
m5_if_d1_z = {d1['y']:.5f};
m5_if_d1_hole_d = {d1['hole_d']:.3f};

m5_if_led1_x = {led1['x']:.5f};
m5_if_led1_z = {led1['y']:.5f};
m5_if_led1_hole_d = {led1['hole_d']:.3f};

m5_if_edge_pts = [
{pts}
];

module m5_if_stadium_2d(w, d) {{
    r = min(d / 2, w / 2);
    hull() for (sx = [-1, 1])
        translate([sx * (w / 2 - r), 0]) circle(r = r, $fn = 28);
}}

module m5_tail_board_interference_cuts() {{
    y0 = m5_if_pcb_y - m5_if_axial;
    y1 = m5_if_pcb_y + m5_if_board_t + m5_if_axial;
    // 满截面板槽：Edge.Cuts 沿 Y 拉伸（板比平滑内腔大 → 卡进环槽）
    // rotate+90 使挤出朝 −Y，故从 y1 起挤到 y0
    translate([0, y1, 0])
        rotate([90, 0, 0])
            linear_extrude(height = y1 - y0)
                polygon(m5_if_edge_pts);

    // Type-C 穿出拍尾
    translate([m5_if_usb_x, m5_if_pcb_y + 0.8, m5_if_usb_z])
        rotate([90, 0, 0])
            linear_extrude(height = (m5_if_pcb_y + 0.8) - (m5_if_butt_y - 3))
                m5_if_stadium_2d(m5_if_usb_w, m5_if_usb_d);

    // 按钮孔（比按柱粗）+ 开关体凹坑
    translate([m5_if_btn_x, m5_if_butt_y - 3, m5_if_btn_z])
        rotate([-90, 0, 0])
            cylinder(d = m5_if_btn_hole_d, h = (m5_if_pcb_y + 1) - (m5_if_butt_y - 3), $fn = 28);
    translate([m5_if_btn_x, m5_if_pcb_y - m5_if_btn_body_h / 2, m5_if_btn_z])
        cube([m5_if_btn_pocket, m5_if_btn_body_h + 0.6, m5_if_btn_pocket], center = true);

    // LED 透光孔
    translate([m5_if_d1_x, m5_if_butt_y - 2.5, m5_if_d1_z])
        rotate([-90, 0, 0])
            cylinder(d = m5_if_d1_hole_d, h = (m5_if_pcb_y + 0.5) - (m5_if_butt_y - 2.5), $fn = 24);
    translate([m5_if_led1_x, m5_if_butt_y - 2.5, m5_if_led1_z])
        rotate([-90, 0, 0])
            cylinder(d = m5_if_led1_hole_d, h = (m5_if_pcb_y + 0.5) - (m5_if_butt_y - 2.5), $fn = 24);
}}
"""
    OUT_SCAD.write_text(text, encoding="utf-8")


# ===== 分区：公开 API =====
def main() -> int:
    data = _extract()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(data, indent=2), encoding="utf-8")
    _write_scad(data)
    print(f"wrote {OUT}  edge_pts={len(data['edge_cuts_xy'])}")
    print(f"wrote {OUT_SCAD}")
    print(
        f"  usb@({data['usb']['x']:.2f},{data['usb']['y']:.2f})  "
        f"sw@({data['button']['x']:.2f},{data['button']['y']:.2f})  "
        f"d1@({data['led_rgb']['x']:.2f},{data['led_rgb']['y']:.2f})"
    )
    return 0


if __name__ == "__main__":
    # Run extract under KiCad Python if needed
    try:
        import pcbnew  # noqa: F401
    except ImportError:
        import subprocess

        raise SystemExit(
            subprocess.call([_kicad_python(), str(Path(__file__).resolve()), *sys.argv[1:]])
        )
    raise SystemExit(main())
